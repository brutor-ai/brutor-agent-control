//! Guard: the third-party licences file of this service. Third-party
//! packages ship unmodified with their licence texts, in each image and in
//! the repository.
//!
//! * `about.toml` accepts exactly the licences `deny.toml` allows, in the
//!   same order: the list is written once, in `deny.toml`, and `cargo about`
//!   (which refuses any other licence, `--fail`) is held to it.
//! * The committed `THIRD_PARTY_LICENSES` lists only packages of the
//!   committed `Cargo.lock`, none of Brutor's own, with the count it states;
//!   a dependency bumped without regenerating the file fails here. The full
//!   comparison (`scripts/third-party-licenses.sh --check`) runs in CI and in
//!   the image build.
//! * The Dockerfile generates the file in its build stage, ships it at
//!   `/usr/share/licenses/brutor/THIRD_PARTY_LICENSES` and next to the
//!   binary, and labels the image with the path.

use std::collections::BTreeSet;
use std::fs;

const DOCKERFILE: &str = "Dockerfile";
const BINARY_DIR: &str = "/app/THIRD_PARTY_LICENSES";
const FIRST_PARTY_PREFIX: &str = "brutor-";

fn read(path: &str) -> String {
    fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}"))
}

/// The quoted strings of the array `key = [ ... ]` (one per line or inline),
/// after the line `section` (or from the top when `section` is empty).
fn array(text: &str, section: &str, key: &str) -> Vec<String> {
    let mut lines = text.lines();
    if !section.is_empty() {
        lines
            .by_ref()
            .find(|l| l.trim() == section)
            .unwrap_or_else(|| panic!("no {section}"));
    }
    let mut inside = false;
    let mut out = Vec::new();
    for line in lines {
        let code = line.split('#').next().unwrap_or("");
        let rest = if !inside {
            let Some(rest) = code.trim().strip_prefix(key) else {
                continue;
            };
            let Some(rest) = rest.trim().strip_prefix('=') else {
                continue;
            };
            inside = true;
            rest.trim()
                .strip_prefix('[')
                .unwrap_or_else(|| panic!("{key} is not an array"))
        } else {
            code
        };
        let (items, done) = match rest.find(']') {
            Some(i) => (&rest[..i], true),
            None => (rest, false),
        };
        out.extend(
            items
                .split(',')
                .map(|s| s.trim().trim_matches('"'))
                .filter(|s| !s.is_empty())
                .map(str::to_string),
        );
        if done {
            return out;
        }
    }
    panic!("{key} = [ not closed");
}

/// `name version` of every package in Cargo.lock.
fn locked() -> BTreeSet<String> {
    let lock = read("Cargo.lock");
    let mut out = BTreeSet::new();
    let mut name = None;
    for line in lock.lines() {
        if let Some(n) = line.strip_prefix("name = ") {
            name = Some(n.trim_matches('"').to_string());
        } else if let Some(v) = line.strip_prefix("version = ")
            && let Some(n) = name.take()
        {
            out.insert(format!("{n} {}", v.trim_matches('"')));
        }
    }
    out
}

/// The `name version` of each line of the file's `Dependencies (N)` list,
/// and N.
fn listed(text: &str) -> (Vec<String>, usize) {
    let mut lines = text.lines();
    let head = lines
        .find(|l| l.starts_with("Dependencies ("))
        .expect("a `Dependencies (N)` line");
    let n = head
        .trim_start_matches("Dependencies (")
        .trim_end_matches(')')
        .parse()
        .expect("N is a number");
    let deps = lines
        .take_while(|l| !l.is_empty())
        .map(|l| {
            let mut it = l.splitn(3, ' ');
            let (name, version) = (it.next().unwrap(), it.next().unwrap_or(""));
            assert!(
                it.next().is_some_and(|e| !e.is_empty()),
                "no licence: {l:?}"
            );
            format!("{name} {version}")
        })
        .collect();
    (deps, n)
}

#[test]
fn about_accepts_exactly_what_deny_allows() {
    let allow = array(&read("deny.toml"), "[licenses]", "allow");
    let accepted = array(&read("about.toml"), "", "accepted");
    assert!(!allow.is_empty());
    assert_eq!(
        accepted, allow,
        "about.toml `accepted` must equal deny.toml `allow`"
    );
}

#[test]
fn the_committed_file_lists_the_locked_third_party_packages() {
    let text = read("THIRD_PARTY_LICENSES");
    assert!(text.starts_with("Third-party licences: "), "the title line");
    assert!(
        text.contains("Generated by cargo-about 0.9.3 from Cargo.lock; do not edit."),
        "the generator line"
    );
    let (deps, n) = listed(&text);
    assert_eq!(deps.len(), n, "the stated count");
    assert!(n > 0);
    let lock = locked();
    for d in &deps {
        assert!(
            !d.starts_with(FIRST_PARTY_PREFIX),
            "a first-party crate is listed: {d}"
        );
        assert!(
            lock.contains(d),
            "{d} is not in Cargo.lock: regenerate with scripts/third-party-licenses.sh"
        );
    }
    assert!(
        text.contains("\n================"),
        "the licence texts follow"
    );
    assert!(!text.contains('\r'), "LF line ends only");
}

#[test]
fn the_image_generates_and_ships_the_file() {
    let d = read(DOCKERFILE);
    assert!(
        d.contains("cargo install --locked --features cli cargo-about@0.9.3"),
        "the build stage installs the pinned generator"
    );
    assert!(
        d.contains("third-party-licenses.sh") && d.contains("--check --out"),
        "the build stage generates the file and fails when the committed copy differs"
    );
    let runtime = d.rsplit("\nFROM ").next().unwrap();
    assert!(
        runtime.contains(" /usr/share/licenses/brutor/THIRD_PARTY_LICENSES\n"),
        "copied to /usr/share/licenses/brutor/"
    );
    assert!(
        runtime.contains(&format!(" {BINARY_DIR}\n")),
        "copied next to the binary"
    );
    assert!(
        runtime.contains(
            "LABEL ai.brutor.third-party-licenses=\"/usr/share/licenses/brutor/THIRD_PARTY_LICENSES\""
        ),
        "the label names the path"
    );
}

#[test]
fn the_array_reader_reads_both_layouts() {
    let t = "[a]\nallow = [\n  \"X\", # c\n  \"Y\",\n]\n[licenses]\nallow = [\"A\", \"B\"]\n";
    assert_eq!(array(t, "[licenses]", "allow"), ["A", "B"]);
    assert_eq!(array(t, "", "allow"), ["X", "Y"]);
}
