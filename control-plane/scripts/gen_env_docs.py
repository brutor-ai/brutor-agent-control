"""
Writes what is generated from the environment-variable registry
(`app/env_registry.py`, `app/env_vars.py`, and the Enterprise Edition's
table where this tree has it):

    .env.example                     the Community Edition's variables
    README.md                        the configuration table (between the markers)
    docs/getting-started-guide.md    the variables a first start needs (between the markers)
    enterprise/.env.example          both editions' variables, each tagged
    enterprise/README.md             the variables only the Enterprise Edition reads

    python scripts/gen_env_docs.py           write them
    python scripts/gen_env_docs.py --check   exit 1 and name the files that differ

Nothing of the environment is read and no application is built: the
tables are data. `tests/test_env_registry.py` and
`enterprise/tests/test_env_registry.py` hold the files to what this
script writes.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Callable, Dict

REPO = Path(__file__).resolve().parents[1]
for _path in (REPO, REPO / "enterprise"):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

from app import env_vars  # noqa: E402,F401 - the table registers itself
from app.env_registry import ENTERPRISE, REGISTRY, View  # noqa: E402

BEGIN = "<!-- env-vars:begin (generated by scripts/gen_env_docs.py; do not edit) -->"
END = "<!-- env-vars:end -->"
REGENERATE = "python scripts/gen_env_docs.py"

# What a first start of the Community Edition needs: the required
# variables, the first administrator's password and Redis.
FIRST_START = ("BRUTOR_DEFAULT_TENANT_ADMIN_PASSWORD", "REDIS_URL")


def has_enterprise() -> bool:
    return (REPO / "enterprise" / "brutor_enterprise" / "env_vars.py").is_file()


def between_markers(text: str, block: str, path: str) -> str:
    """`text` with what stands between the markers replaced by `block`."""
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise SystemExit(f"{path}: the markers of the generated table are missing or not in order")
    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n\n{block}\n{END}{tail}"


def community_documents(read: Callable[[str], str]) -> Dict[str, str]:
    view = REGISTRY.view(enterprise=False)
    first_start = view.markdown(only=lambda var: var.required or var.name in FIRST_START)
    return {
        ".env.example": view.env_example("app/env_vars.py", REGENERATE),
        "README.md": between_markers(read("README.md"), view.markdown(), "README.md"),
        "docs/getting-started-guide.md": between_markers(
            read("docs/getting-started-guide.md"), first_start, "docs/getting-started-guide.md"
        ),
    }


def enterprise_documents(read: Callable[[str], str]) -> Dict[str, str]:
    import brutor_enterprise.env_vars  # noqa: F401 - the table registers itself

    view = REGISTRY.view(enterprise=True)
    own = View(view.title, [var for var in view.vars if var.edition == ENTERPRISE])
    return {
        "enterprise/.env.example": view.env_example(
            "app/env_vars.py and enterprise/brutor_enterprise/env_vars.py", REGENERATE
        ),
        "enterprise/README.md": between_markers(read("enterprise/README.md"), own.markdown(), "enterprise/README.md"),
    }


def documents() -> Dict[str, str]:
    def read(path: str) -> str:
        return (REPO / path).read_text(encoding="utf-8")

    found = community_documents(read)
    if has_enterprise():
        found.update(enterprise_documents(read))
    return found


def main(arguments: list) -> int:
    check = "--check" in arguments
    differing = []
    for path, text in documents().items():
        target = REPO / path
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == text:
            continue
        differing.append(path)
        if not check:
            target.write_text(text, encoding="utf-8")
    if check and differing:
        print("not what the registry generates (run: " + REGENERATE + "): " + ", ".join(differing), file=sys.stderr)
        return 1
    if not check:
        print("written: " + (", ".join(differing) if differing else "nothing (all up to date)"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
