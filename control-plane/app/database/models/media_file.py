"""
Media File registry.

Generated and uploaded media (images, audio, video, transcribe input)
is persisted to object storage (S3 or MinIO in the trial bundle).
Chat messages refer to assets by stable ``brutor_file_id``; the
portal asks the gateway for short-lived signed URLs at render time.
This row is the metadata index — bytes live in object storage,
addressed by ``object_key``.

Why row + storage split:
  * Re-rendering an old chat after a signed-URL TTL expires only
    requires looking up the row and minting a fresh URL — no
    "broken image" once a URL has aged out.
  * Per-tenant policy enforcement (quotas, retention, deletion) is
    applied at the row level, not at the bytes level.
  * Storage backend can be swapped (S3 → R2, MinIO → Garage) without
    any chat history rewrite — the ``object_key`` is the only thing
    that needs migrating.

The row is written by the Rust gateway-core proxy when an upstream
provider returns a binary, or when a portal user uploads input
(STT). Gateway-control owns the schema and exposes admin queries;
runtime CRUD is in the proxy.
"""

from datetime import datetime, timezone
from typing import Any, Dict, Optional

from sqlalchemy import (
    BigInteger,
    Column,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
)
from sqlalchemy.sql import func

from app.database import Base


class MediaFile(Base):
    """
    Tenant-scoped registry of media assets stored in object storage.

    Lifecycle:
      created → expires_at hits → soft-deleted (deleted_at set) →
      after 7 days, GC sweep removes the underlying object and the row.

    The signed-URL TTL is a separate concern (minutes-scale, applied
    when ``GET /v1/proxy/files/{id}/url`` is called). ``expires_at``
    governs the *retention* of the bytes themselves.
    """

    __tablename__ = "media_files"

    # ------------------------------------------------------------------
    # Identity
    # ------------------------------------------------------------------

    # The wire-stable file id surfaced as ``brutor_file_id`` on the
    # chat-stream protocol. ULID-shaped string (e.g. ``file_01HX…``).
    # Generated by the Rust proxy at row-insert time.
    id = Column(
        String(64),
        primary_key=True,
        comment=(
            "Stable, ULID-based file id surfaced as brutor_file_id "
            "on the wire. Chat messages reference this — never the "
            "object_key or a signed URL."
        ),
    )

    tenant_id = Column(
        String(255),
        ForeignKey("tenants.id", ondelete="CASCADE"),
        nullable=False,
        comment="Tenant the file belongs to. Cross-tenant access denied at URL-issue.",
    )

    # ------------------------------------------------------------------
    # Asset description
    # ------------------------------------------------------------------

    # 'image' | 'audio_speech' | 'audio_transcription_input' |
    # 'video' | 'document' | 'other'. Mirrors LLModelMode for the
    # generation modes plus 'document'/'other' for the upload-only
    # paths (e.g. RAG ingestion).
    kind = Column(
        String(40),
        nullable=False,
        comment=(
            "Asset class: 'image', 'audio_speech', "
            "'audio_transcription_input', 'video', 'document', or "
            "'other'. Drives bucket-prefix layout and retention "
            "default."
        ),
    )

    mime_type = Column(
        String(120),
        nullable=False,
        comment="IANA media type, e.g. 'image/png', 'audio/mp3'.",
    )

    size_bytes = Column(
        BigInteger,
        nullable=False,
        comment=(
            "Byte length of the stored object. Used for quota "
            "enforcement at write time (sum of size_bytes for "
            "non-deleted rows ≤ tenant.media_storage_quota_bytes)."
        ),
    )

    # SHA-256 hex digest of the bytes. Used for de-duplication
    # (a tenant uploading the same file twice gets the same id) and
    # forensic verification (proxy logs reference the hash; an
    # operator can confirm that the bytes fetched from storage match
    # what was logged at ingest).
    content_hash = Column(
        String(64),
        nullable=True,
        comment=(
            "SHA-256 hex digest of the stored bytes. Nullable for "
            "streaming uploads where the hash isn't computed at "
            "ingest. Set once available."
        ),
    )

    # The provider-or-bucket-relative key. Format:
    #   ${tenant_id}/${kind}/${yyyy}/${mm}/${file_id}.${ext}
    # The leading tenant prefix is what the bucket-policy SCP uses to
    # deny cross-tenant access — so this column is the primary
    # isolation control.
    object_key = Column(
        String(1024),
        nullable=False,
        comment=(
            "Bucket-relative key. Layout: "
            "${tenant_id}/${kind}/${yyyy}/${mm}/${file_id}.${ext}. "
            "The leading tenant_id segment is the isolation boundary "
            "the bucket policy enforces."
        ),
    )

    # The bucket name is configured per gateway-core deployment
    # (``MEDIA_BUCKET``) so we don't store it on every row. Kept here
    # only as a forensic note when a bucket migration happens — null
    # for rows that live in the currently-configured bucket.
    storage_bucket_override = Column(
        String(255),
        nullable=True,
        comment=(
            "Set only for rows that live in a non-default bucket "
            "(e.g. during a backend migration). NULL means the "
            "currently-configured MEDIA_BUCKET."
        ),
    )

    # ------------------------------------------------------------------
    # Provenance
    # ------------------------------------------------------------------

    # Optional FK to a chat row. Kept nullable because gateway-control
    # doesn't model chat history (the portal stores chats in
    # IndexedDB) and uploads from non-chat surfaces (admin UI, RAG
    # ingestion) won't have a chat_id either.
    chat_id = Column(
        String(64),
        nullable=True,
        comment=(
            "Optional client-supplied chat id this file was generated "
            "for. Allows 'delete this chat' to fan out to file "
            "deletes. Not a FK — chat history is portal-side."
        ),
    )

    # The model that produced or consumed this file (FK to llm_model
    # so cost dashboards can roll up per-model media spend).
    model_id = Column(
        String(100),
        ForeignKey("llm_model.id", ondelete="SET NULL"),
        nullable=True,
        comment="FK to llm_model for the model that generated/consumed this file.",
    )

    # User identity is captured by the upstream proxy log; we don't
    # duplicate the FK here (different ID spaces for admin vs end
    # users), but we keep the string for cost-by-user reporting.
    actor_id = Column(
        String(255),
        nullable=True,
        comment="User identifier (admin or end-user) who triggered this file.",
    )

    # Optional human-readable label set by the user (e.g. "logo.png").
    # Storage path uses the file_id, never this — purely UX.
    display_name = Column(
        String(500),
        nullable=True,
        comment="Optional UX label. Storage path is keyed on file_id; this is display-only.",
    )

    # ------------------------------------------------------------------
    # Lifecycle
    # ------------------------------------------------------------------

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Retention. Default 30 days from created_at; overridable per
    # tenant. After this point, the GC sweep flips ``deleted_at`` and
    # the underlying object is hard-deleted 7 days later.
    expires_at = Column(
        DateTime(timezone=True),
        nullable=False,
        comment=(
            "Retention deadline. After this, GC sweep soft-deletes "
            "the row; after a further 7-day recovery window, the "
            "underlying object is removed."
        ),
    )

    # Soft delete. Once set, signed-URL issuance refuses the file.
    # Kept around for the 7-day recovery window so an operator can
    # restore by clearing this column.
    deleted_at = Column(
        DateTime(timezone=True),
        nullable=True,
        comment=(
            "Soft-delete marker. Set when the user deletes the file "
            "or when GC hits the retention deadline. The underlying "
            "object is hard-removed 7 days after this."
        ),
    )

    # Pre-signed URL audit field. Stored as a count + most-recent
    # timestamp so dashboards can flag "asset never accessed" without
    # joining onto proxy_logs.
    access_count = Column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
        comment="Number of signed URLs issued for this file.",
    )

    last_accessed_at = Column(
        DateTime(timezone=True),
        nullable=True,
        comment="Wall-clock time of the most recent signed-URL issuance.",
    )

    # ------------------------------------------------------------------
    # Indexes
    # ------------------------------------------------------------------

    __table_args__ = (
        # Quota enforcement and tenant queries — "sum size_bytes for
        # tenant X where deleted_at IS NULL". Partial-NULL index keeps
        # this cheap even for tenants with millions of historical
        # files.
        Index(
            "ix_media_files_tenant_active",
            "tenant_id",
            "deleted_at",
        ),
        # GC sweep — "find expired rows that haven't been
        # soft-deleted yet". Composite (expires_at, deleted_at)
        # supports both the soft-delete pass and the hard-delete
        # pass.
        Index(
            "ix_media_files_lifecycle",
            "expires_at",
            "deleted_at",
        ),
        # "Delete this chat" fanout.
        Index(
            "ix_media_files_chat",
            "tenant_id",
            "chat_id",
        ),
        # Per-model cost rollups.
        Index(
            "ix_media_files_model",
            "tenant_id",
            "model_id",
        ),
        {
            "comment": (
                "Tenant-scoped registry of media assets stored in "
                "object storage. Bytes live in S3/MinIO; this row is "
                "the addressable index."
            )
        },
    )

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    @property
    def is_alive(self) -> bool:
        """True if the file is currently issuable as a signed URL."""
        if self.deleted_at is not None:
            return False
        # expires_at is non-null by NOT NULL; compare in UTC.
        now = datetime.now(timezone.utc)
        ends_at = self.expires_at
        if ends_at.tzinfo is None:
            ends_at = ends_at.replace(tzinfo=timezone.utc)
        return now < ends_at

    def soft_delete(self) -> None:
        """Mark for hard-delete in the next GC sweep + 7 days."""
        self.deleted_at = datetime.now(timezone.utc)

    def to_dict(self) -> Dict[str, Any]:
        """Wire-format dict for admin/proxy responses.

        Note: ``object_key`` and ``storage_bucket_override`` are
        deliberately omitted — clients should never see them. Use
        ``GET /v1/proxy/files/{id}/url`` to mint a signed URL.
        """
        return {
            "id": self.id,
            "tenant_id": self.tenant_id,
            "kind": self.kind,
            "mime_type": self.mime_type,
            "size_bytes": self.size_bytes,
            "content_hash": self.content_hash,
            "chat_id": self.chat_id,
            "model_id": self.model_id,
            "actor_id": self.actor_id,
            "display_name": self.display_name,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "expires_at": self.expires_at.isoformat() if self.expires_at else None,
            "deleted_at": self.deleted_at.isoformat() if self.deleted_at else None,
            "access_count": self.access_count or 0,
            "last_accessed_at": (
                self.last_accessed_at.isoformat() if self.last_accessed_at else None
            ),
        }

    def __repr__(self) -> str:
        return (
            f"<MediaFile(id={self.id}, tenant={self.tenant_id}, "
            f"kind={self.kind}, size={self.size_bytes})>"
        )
