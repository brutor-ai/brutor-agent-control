"""
# a171_audit_digests migration drift suite — content digests, trace context, tool
# provenance, deciding model.

Same reasoning as a131_ai_system_runs: fresh installs build `proxy_logs` from the model
(create_all + stamp) and never run this migration, while the Rust core
writes every one of these columns positionally. A column present in one
place and absent in another persists as a NULL that reads exactly like
"nothing was recorded" — which is the one thing an integrity claim cannot
afford. So the model, the migration, the core's INSERT and the core's test
fixture are pinned against each other here.
"""

from __future__ import annotations

from unittest.mock import MagicMock

import pytest

from app.database.models.proxy_log import ProxyLog
from tests.core_repo import core_repo_path, core_source


COLUMNS = {
    "request_content_hash": 64,
    "response_content_hash": 64,
    "trace_id": 32,
    "span_id": 16,
    "server_version": 64,
    "tool_definition_hash": 64,
    "deciding_model": 255,
}


class TestModelParity:
    @pytest.mark.parametrize(("name", "length"), sorted(COLUMNS.items()))
    def test_model_declares_each_column(self, name, length):
        col = ProxyLog.__table__.c[name]
        assert col.type.length == length
        assert col.nullable, f"{name} must be nullable — absence is recorded as absence"

    def test_model_declares_the_trace_index(self):
        names = {i.name for i in ProxyLog.__table__.indexes}
        assert "ix_proxy_logs_trace" in names, "fresh installs build indexes from the model"

    def test_to_dict_exposes_each_column(self):
        row = MagicMock(spec=ProxyLog)
        for name in COLUMNS:
            setattr(row, name, f"value-{name}")
        d = ProxyLog.to_dict(row)
        for name in COLUMNS:
            assert d[name] == f"value-{name}", f"to_dict drops {name} — the API would never show it"


class TestCoreParity:
    """The Rust core is the only writer of these columns. Read where
    `BRUTOR_CORE_REPO` says (`tests/core_repo.py`): skipped without it."""

    def test_fixture_schema_carries_each_column(self):
        sql = (core_repo_path() / "tests" / "migrations" / "00000000000000_schema.sql").read_text()
        # The fixture is a pg_dump of a fresh install (regenerated by
        # `regen-schema.sh`), so the columns sit inside the CREATE TABLE
        # body; a hand-appended `ALTER TABLE ... ADD COLUMN` is accepted too.
        import re

        table = re.search(r"CREATE TABLE public\.proxy_logs \((.*?)\n\);", sql, re.S)
        assert table, "core test fixture has no proxy_logs table"
        body = table.group(1)
        for name in COLUMNS:
            assert (
                re.search(rf"^\s+{name} ", body, re.M) or f"ADD COLUMN {name} " in sql
            ), f"core test fixture lacks {name}"

    def test_writer_inserts_and_binds_each_column(self):
        src = core_source("services", "background_writer.rs").read_text()
        for name in COLUMNS:
            assert f".push_bind(&log.{name})" in src, f"writer never binds {name}"
            assert f" {name}," in src or f" {name}\n" in src, f"writer INSERT list lacks {name}"

    def test_the_hash_covers_witnessed_columns_and_not_asserted_ones(self):
        # a171_audit_digests put the digests and tool provenance inside the hash, and
        # `deciding_model` is in it too — it is resolved before the batch is
        # sealed and the sibling it derives from may be pruned or on another
        # writer's chain. The caller's trace ids stay outside as asserted
        # join keys. The full coverage contract lives in
        # tests/test_audit_chain_v3.py.
        from app.services.audit_chain_canonical import CHAIN_EXCLUDED_COLUMNS, V3_FIELDS

        chain = core_source("services", "audit_chain.rs").read_text()
        for covered in ("request_content_hash", "response_content_hash", "server_version", "tool_definition_hash"):
            assert covered in V3_FIELDS, f"{covered} not in canonical bytes"
            assert f'"{covered}"' in chain
        assert "deciding_model" in V3_FIELDS
        for asserted in ("trace_id", "span_id"):
            assert CHAIN_EXCLUDED_COLUMNS[asserted] == "CallerCorrelation"
            assert f'("{asserted}", Excluded::CallerCorrelation)' in chain, (
                f"{asserted} is asserted and must stay outside the hash"
            )
