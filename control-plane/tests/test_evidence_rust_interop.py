"""
# Cross-language evidence parity — Rust (core) ↔ Python (control plane)

The core seals action records, builds the tenant Merkle log and bundles;
the control plane re-derives parts of the same artefacts without any
crypto library (the control plane does JSON rule checks only; cryptography
is the core's) — record ids and digests it displays, inclusion proofs it
serves from stored nodes (`app/services/evidence/merkle.py`), bundle
digests it compares. This file pins that both languages agree byte for
byte on artefacts the Rust side produced:

  * RFC 8785 canonical bytes (UTF-16 key order!) and `record_id` =
    SHA-256(JCS(record minus record_id)), via `sealing.canonical_bytes`;
  * salted digests SHA-256(JCS(value) || "|" || salt) and plain / UTF-8
    reference digests over literal preimages;
  * RFC 6962 leaf hashes of the Signed Statements, the stored-node set the
    append algorithm produces, roots and inclusion paths from that node set,
    and RFC 9162 proof verification;
  * bundle digests = SHA-256(JCS(bundle minus countersignatures)).

Fixture: `tests/fixtures/evidence_interop_v1.json`, generated by the core's
`cargo run -p brutor-verify --example gen-vectors` (the core's
`vectors_are_up_to_date` test fails when it drifts). Never hand-edit it.
"""

from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

import pytest

from app.services.compliance import sealing
from app.services.evidence import merkle

FIXTURE = Path(__file__).parent / "fixtures" / "evidence_interop_v1.json"


@pytest.fixture(scope="module")
def fx():
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _at(value, path: str):
    """Resolve `a.b[0].c` in a record (the fixture's preimage paths)."""
    cur = value
    for part in path.split("."):
        name, _, idx = part.partition("[")
        cur = cur[name]
        if idx:
            cur = cur[int(idx.rstrip("]"))]
    return cur


def test_fixture_is_the_rust_generated_v1(fx):
    assert fx["version"] == 1
    assert "gen-vectors" in fx["generator"]
    assert len(fx["records"]) >= 20
    assert fx["log"]["tree_size"] == len(fx["log"]["leaf_hashes"])


def test_jcs_matches_rust_on_every_accepted_case(fx):
    accepted = [c for c in fx["canon"] if "canonical" in c]
    assert any("U+10000" in c["description"] for c in accepted), "UTF-16 ordering case missing"
    for c in accepted:
        got = sealing.canonical_bytes(json.loads(c["input"]))
        assert got.decode("utf-8") == c["canonical"], c["description"]
        assert hashlib.sha256(got).hexdigest() == c["sha256"], c["description"]


def test_record_ids_recompute_from_canonical_bytes(fx):
    for r in fx["records"]:
        body = {k: v for k, v in r["record"].items() if k != "record_id"}
        canon = sealing.canonical_bytes(body)
        assert canon.decode("utf-8") == r["canonical"], r["name"]
        assert hashlib.sha256(canon).hexdigest() == r["record_id"] == r["record"]["record_id"], r["name"]


def test_preimage_digests_recompute(fx):
    schemes = set()
    for r in fx["records"]:
        for path, spec in r["preimages"].items():
            scheme = spec["scheme"]
            schemes.add(scheme)
            if scheme == "jcs":
                want = sealing.json_digest(spec["value"])
            elif scheme == "jcs_salted":
                salt = r["record"]["attestation"]["digest_salt"]
                want = hashlib.sha256(
                    sealing.canonical_bytes(spec["value"]) + b"|" + salt.encode("ascii")
                ).hexdigest()
            elif scheme == "utf8":
                want = sealing.text_digest(spec["value"])
            else:  # pragma: no cover - a new scheme must be added here
                pytest.fail(f"unknown preimage scheme {scheme}")
            assert _at(r["record"], path) == want, f"{r['name']}: {path}"
    assert schemes == {"jcs", "jcs_salted", "utf8"}


def test_statement_leaf_hashes(fx):
    for r in fx["records"]:
        stmt = base64.b64decode(r["statement_b64"])
        assert merkle.leaf_hash(stmt) == r["leaf_hash"], r["name"]
        # hash-envelope mode: the COSE payload is the raw record_id; it sits
        # at the end of the statement's payload bstr (0x58 0x20 ‖ 32 bytes).
        assert bytes.fromhex(r["record_id"]) in stmt, r["name"]


def test_node_set_roots_and_inclusion_from_stored_nodes(fx):
    log = fx["log"]
    nodes: dict = {}
    for i, leaf in enumerate(log["leaf_hashes"]):
        merkle.append_leaf(nodes, i, leaf)
    want = {(n["level"], n["index"]): n["hash"] for n in log["nodes"]}
    assert nodes == want, "the Python append algorithm stores a different node set"
    get = merkle.store_getter(want)
    for size, root in log["roots"].items():
        assert merkle.root_hash(get, int(size)) == root, size
    for c in log["inclusion"]:
        path = merkle.inclusion_path(get, c["index"], c["tree_size"])
        assert path == c["path"], c
        leaf = log["leaf_hashes"][c["index"]]
        assert merkle.verify_inclusion(leaf, c["index"], c["tree_size"], path, c["root"]) is c["expect"]


def test_bundle_proofs_and_digests(fx):
    for b in fx["bundles"]:
        bundle = b["bundle"]
        body = {k: v for k, v in bundle.items() if k != "countersignatures"}
        assert sealing.json_digest(body) == b["bundle_digest"], b["file"]
        # Every record's proof folds to a root the Python verifier accepts
        # with the leaf it derives itself from the statement bytes …
        roots = set()
        by_id = {r["record"]["record_id"]: r for r in bundle["records"]}
        for p in bundle["proofs"]:
            stmt = base64.b64decode(by_id[p["record_id"]]["statement_b64"])
            leaf = merkle.leaf_hash(stmt)
            assert len(p["path"]) == merkle.path_length(p["leaf_index"], p["tree_size"])
            roots.add(_fold(leaf, p["leaf_index"], p["tree_size"], p["path"]))
        # … and all proofs of one bundle agree on that root (the newest head's).
        assert len(roots) == 1, b["file"]
        root = roots.pop()
        for p in bundle["proofs"]:
            stmt = base64.b64decode(by_id[p["record_id"]]["statement_b64"])
            assert merkle.verify_inclusion(merkle.leaf_hash(stmt), p["leaf_index"], p["tree_size"], p["path"], root)
        # A tampered path is refused.
        p = bundle["proofs"][0]
        if p["path"]:
            stmt = base64.b64decode(by_id[p["record_id"]]["statement_b64"])
            assert not merkle.verify_inclusion(
                merkle.leaf_hash(stmt), p["leaf_index"], p["tree_size"], p["path"][:-1], root
            )


def _fold(leaf: str, index: int, size: int, path: list) -> str:
    """RFC 9162 §2.1.3.2 root from an inclusion path (test-local; the module
    only exposes the boolean verifier)."""
    fn, sn, r = index, size - 1, leaf
    for p in path:
        if fn & 1 or fn == sn:
            r = merkle.node_hash(p, r)
            if not fn & 1:
                while fn and not fn & 1:
                    fn >>= 1
                    sn >>= 1
        else:
            r = merkle.node_hash(r, p)
        fn >>= 1
        sn >>= 1
    return r


@pytest.mark.xfail(
    strict=True,
    reason=(
        "Known divergence: sealing.canonical_bytes rewrites integral floats to "
        "ints and passes other floats through, whereas the core refuses any "
        "float (digest hygiene: a digested value carries no float). CP-side digests are only ever "
        "compared by the CP itself today (rubric/documentation digests); make "
        "canonical_bytes refuse floats before a third party must reproduce one."
    ),
)
def test_float_and_unsafe_integer_cases_are_refused_like_rust(fx):
    refused = [c for c in fx["canon"] if "error" in c]
    assert refused
    for c in refused:
        with pytest.raises((ValueError, TypeError)):
            sealing.canonical_bytes(json.loads(c["input"]))
