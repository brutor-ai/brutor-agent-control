/// OpenAI-compatible request body. We accept all the fields OpenAI
/// does so a chosen client SDK can target this endpoint without
/// rewriting; unknown fields are tolerated (Serde `default`).
#[derive(Debug, Deserialize)]
struct ImageGenRequest {
    model: String,
    prompt: String,
    #[serde(default = "default_n")]
    n: i32,
    #[serde(default = "default_size")]
    size: String,
    /// OpenAI DALL·E 3 / gpt-image-1 only — DALL·E 2 rejects this
    /// field with `unknown_parameter`. Optional so we can forward
    /// it only when the caller actually set it; the per-model
    /// whitelist (`supported_image_qualities`) is enforced at the
    /// validation step below regardless.
    #[serde(default)]
    quality: Option<String>,
    /// `"url"` (default) or `"b64_json"`. We always persist the
    /// bytes; this only affects whether we *also* return them
    /// inline. b64_json is useful for clients that don't speak
    /// HTTPS to fetch the signed URL.
    #[serde(default = "default_response_format")]
    response_format: String,
    /// OpenAI: `"vivid"` | `"natural"`. Forwarded verbatim.
    #[serde(default)]
    style: Option<String>,
    /// Optional client-supplied chat id so "delete this chat"
    /// fanout can find the file.
    #[serde(default)]
    chat_id: Option<String>,
    /// User-facing label.
    #[serde(default)]
    display_name: Option<String>,
}

fn default_n() -> i32 {
    1
}
fn default_size() -> String {
    "1024x1024".into()
}
fn default_response_format() -> String {
    "url".into()
}

#[derive(Debug, Serialize)]
struct ImageGenResponse {
    created: i64,
    data: Vec<ImageDataItem>,
    brutor_cost_usd: f64,
    brutor_model_id: String,
}

#[derive(Debug, Serialize)]
struct ImageDataItem {
    /// Signed URL for the persisted image, or null when
    /// `response_format=b64_json` was requested.
    #[serde(skip_serializing_if = "Option::is_none")]
    url: Option<String>,
    /// Base64-encoded bytes when `response_format=b64_json`.
    #[serde(skip_serializing_if = "Option::is_none")]
    b64_json: Option<String>,
    /// OpenAI-only: the model may rewrite the prompt for safety /
    /// compliance and surface the rewrite back to the caller.
    #[serde(skip_serializing_if = "Option::is_none")]
    revised_prompt: Option<String>,
    brutor_file_id: String,
    brutor_mime_type: String,
}

