//! Image generation route.
//!
//! ## Endpoint
//!
//! `POST /v1/proxy/llm/images/generations`
//!
//! OpenAI-compatible request body. Response shape mirrors OpenAI
//! plus Brutor-specific fields:
//!
//! ```json
//! {
//!   "created": 1730000000,
//!   "data": [
//!     {
//!       "url": "https://media.brutor.ai/...?<signed>",
//!       "b64_json": null,
//!       "revised_prompt": "...",
//!       "brutor_file_id": "file_01HX...",
//!       "brutor_mime_type": "image/png"
//!     }
//!   ],
//!   "brutor_cost_usd": 0.040,
//!   "brutor_model_id": "llm-..."
//! }
//! ```
//!
//! ## Pipeline
//!
//! 1. Authenticate the caller (an API key, or a portal session where the
//!    Portal is composed) → `(tenant_id, actor_id)`.
//! 2. Resolve the model from the cache by `model` field.
//!    Reject with 404 if missing, 400 if not image-mode.
//! 3. Validate `size`, `quality`, `n` against the model's
//!    whitelists.
//! 4. Apply prompt guardrails (existing chain).
//! 5. Dispatch to the provider adapter — currently OpenAI dall-e
//!    is the only first-class backend; other providers fall
//!    through to a "not yet implemented" 501 with a clear hint.
//! 6. Persist the generated bytes via `media_storage.put`.
//! 7. Insert one `media_files` row per image, with
//!    `kind='image'`, `model_id`, `actor_id`, `mime_type`, etc.
//! 8. Mint signed URLs and return.
//! 9. Log to `proxy_logs` with cost + duration.

use axum::{
    Json, Router,
    extract::State,
    http::{HeaderMap, StatusCode},
    response::{IntoResponse, Response},
    routing::post,
};
use bytes::Bytes;
use chrono::{Duration as ChronoDuration, Utc};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use std::time::{Duration, Instant};

use crate::middleware::tenant::TenantContext;
use crate::models::db::LlmModel;
use crate::services::SharedState;
use crate::services::llm_preflight;
use crate::services::media_storage::{MediaKind, ObjectKey, StorageError};
use crate::services::multimodal_pipeline::{
    MediaUnitCounters, MultimodalOutcome, abandon_gate, acquire_gate, multimodal_preflight,
    record_multimodal_outcome,
};

const DEFAULT_RETENTION_DAYS: i64 = 30;
/// Hard cap on concurrent image-row writes per request. Beyond this
/// the orchestration layer would need a streaming pipeline; today's
/// `n` cap of 10 fits comfortably within the simple per-image loop.
const MAX_IMAGES_PER_REQUEST_CEILING: i32 = 10;

pub fn router() -> Router<SharedState> {
    Router::new().route("/", post(generate))
}

