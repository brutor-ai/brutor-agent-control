"""Generate `tests/migrations/00000000000000_schema.sql` from `schema.sql`.

`schema.sql` is the `pg_dump --schema-only` fixture (`tests/migrations/
regen-schema.sh` writes it). Every `#[sqlx::test]` database used to replay
that whole dump, about 13 000 lines, once per test: the suite's dominant
cost. The migration this script writes wraps the dump in a guard:

* a database cloned from a template holding THIS schema (stamped with its
  SHA-256 by `prepare-test-template.sh`) skips the replay; sqlx's
  `CREATE DATABASE` clones `template1`, so a stamped `template1` makes
  every test database start with the schema already in place;
* a database cloned from a template holding a DIFFERENT schema fails
  loudly, rather than testing against a stale schema;
* anything else (no template prepared) replays the dump, as before.

Usage:
    ./tests/schema/gen-migration.py            # rewrite the migration
    ./tests/schema/gen-migration.py --check    # fail if it is stale (CI, guard test)
"""

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCHEMA = HERE / "schema.sql"
TARGET = HERE.parent / "migrations" / "00000000000000_schema.sql"
STAMP_TABLE = "_brutor_test_template"
DOLLAR = "$brutor_schema$"


def render(schema: str) -> str:
    if DOLLAR in schema:
        sys.exit(f"ERROR: {SCHEMA.name} contains {DOLLAR}; pick another quote tag")
    digest = hashlib.sha256(schema.encode()).hexdigest()
    return f"""-- GENERATED by tests/schema/gen-migration.py from tests/schema/schema.sql.
-- Do not edit: run tests/migrations/regen-schema.sh (or gen-migration.py).
-- schema-sha256: {digest}
--
-- Skips the schema replay when this database was cloned from a
-- template stamped with this exact schema (tests/schema/
-- prepare-test-template.sh); refuses a template holding another schema;
-- otherwise replays the dump.
DO $brutor_guard$
DECLARE
    stamped text;
BEGIN
    IF to_regclass('public.{STAMP_TABLE}') IS NOT NULL THEN
        SELECT schema_sha256 INTO stamped FROM public.{STAMP_TABLE};
        IF stamped IS DISTINCT FROM '{digest}' THEN
            RAISE EXCEPTION 'test template holds schema %, the fixture is {digest}: re-run tests/schema/prepare-test-template.sh', stamped;
        END IF;
        -- The stamp is bookkeeping: drop it so the database matches a replayed one.
        DROP TABLE public.{STAMP_TABLE};
        RETURN;
    END IF;
    EXECUTE {DOLLAR}
{schema}{DOLLAR};
END
$brutor_guard$;

SELECT pg_catalog.set_config('search_path', 'public', false);
"""


def main() -> int:
    schema = SCHEMA.read_text()
    out = render(schema)
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != out:
            print(
                f"STALE: {TARGET.relative_to(HERE.parent.parent)} does not match "
                f"{SCHEMA.name}.\nFix: ./tests/schema/gen-migration.py and commit the result.",
                file=sys.stderr,
            )
            return 1
        print("Migration wrapper is up to date.")
        return 0
    TARGET.write_text(out)
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
