# Build the static, offline evidence verifier page:
#
#   crates/brutor-verify/build-web.sh            # → crates/brutor-verify/dist/
#   crates/brutor-verify/build-web.sh OUT_DIR
#
# dist/ holds index.html, brutor_verify.js (wasm-bindgen glue, classic
# script), brutor_verify_bg.wasm, and brutor_verify_wasm.js (the same wasm
# embedded as base64) so the page also works when opened straight from disk
# (file://), where browsers refuse to fetch() a sibling file. No server, no
# network, no analytics. The docs site hosts dist/ as-is.
#
# Needs: rustup target wasm32-unknown-unknown, and wasm-bindgen-cli at the
# exact version of the wasm-bindgen crate in Cargo.lock:
#   cargo install wasm-bindgen-cli --version "$(cargo pkgid wasm-bindgen | sed 's/.*[@#]//')"
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${1:-$HERE/dist}"
TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/target}"
WASM_BINDGEN="${WASM_BINDGEN:-wasm-bindgen}"

command -v "$WASM_BINDGEN" >/dev/null || {
  echo "wasm-bindgen CLI not found (set WASM_BINDGEN or install wasm-bindgen-cli)" >&2
  exit 2
}
want="$(cd "$ROOT" && cargo pkgid wasm-bindgen 2>/dev/null | sed 's/.*[@#]//')"
have="$("$WASM_BINDGEN" --version | awk '{print $2}')"
if [ -n "$want" ] && [ "$want" != "$have" ]; then
  echo "wasm-bindgen CLI $have does not match the wasm-bindgen crate $want" >&2
  exit 2
fi

(cd "$ROOT" && cargo build -p brutor-verify --lib --release \
  --target wasm32-unknown-unknown --no-default-features --features wasm)

mkdir -p "$OUT"
"$WASM_BINDGEN" --target no-modules --no-typescript \
  --out-dir "$OUT" --out-name brutor_verify \
  "$TARGET_DIR/wasm32-unknown-unknown/release/brutor_verify.wasm"

{
  printf '// Generated by build-web.sh: brutor_verify_bg.wasm as base64, so the page\n'
  printf '// works from file:// without fetch().\n'
  printf 'window.BRUTOR_VERIFY_WASM_B64 = "'
  base64 < "$OUT/brutor_verify_bg.wasm" | tr -d '\n'
  printf '";\n'
} > "$OUT/brutor_verify_wasm.js"

cp "$HERE/web/index.html" "$OUT/index.html"
(cd "$OUT" && shasum -a 256 index.html brutor_verify.js brutor_verify_bg.wasm brutor_verify_wasm.js > SHA256SUMS)
echo "wrote $OUT"
ls -l "$OUT"
